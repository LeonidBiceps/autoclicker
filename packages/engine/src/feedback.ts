/**
 * Единый адрес поддержки студии — один на все игры, чтобы не менять его в
 * трёх местах при смене почты. Значение-заглушка: ПОДСТАВЬТЕ РЕАЛЬНЫЙ АДРЕС
 * до публикации, иначе кнопка «Написать разработчику» будет открывать письмо
 * в никуда.
 */
export const SUPPORT_EMAIL = 'feedback@example.com';

/**
 * Письмо разработчику через `mailto:`.
 *
 * Без бэкенда и аккаунта разработчика это самый дешёвый рабочий канал: не
 * нужен сервер, работает в любом браузере, игрок пишет в привычном почтовом
 * клиенте. `window.open` вместо прямой навигации — чтобы не увести игрока со
 * страницы игры, если почтовый клиент не настроен и переход некуда.
 */
export function openMailFeedback(email: string, subject: string, body: string): void {
  // Сам адрес не кодируем: `@` в percent-encoded виде (`%40`) часть почтовых
  // клиентов не разбирает, хотя RFC формально это допускает.
  const url = `mailto:${email}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  window.open(url, '_blank');
}
